# ======================================================
# CSV CLEANING PIPELINE FOR MQTT/TCP TRAFFIC
# This script cleans raw CSV files extracted from PCAP
# and prepares them for machine learning analysis.
# ======================================================

# Import pandas for data manipulation and cleaning
import pandas as pd

# Allows searching files using patterns (e.g., *.csv)
import glob

# Provides utilities for working with file system paths
import os


# ======================================================
# ROBUST DIRECTORY CONFIGURATION
# ======================================================

# Obtain the absolute path of the current script
# This ensures the script works regardless of the execution directory
BASE_DIR = os.path.dirname(os.path.abspath(__file__))

# Directory containing raw CSV files generated by TShark
CSV_RAW_DIR = os.path.join(BASE_DIR, "..", "csv_raw")

# Directory where cleaned CSV files will be stored
CSV_CLEAN_DIR = os.path.join(BASE_DIR, "..", "csv_clean")

# Create output directory if it does not exist
os.makedirs(CSV_CLEAN_DIR, exist_ok=True)

# Print directory paths for verification
print("CSV_RAW_DIR:", CSV_RAW_DIR)
print("CSV_CLEAN_DIR:", CSV_CLEAN_DIR)


# ======================================================
# DATA CLEANING FUNCTION
# ======================================================

def clean_dataframe(df):
    """
    Controlled cleaning procedure for MQTT/TCP network traffic.

    The objective is to remove incomplete records while preserving
    both legitimate and malicious traffic patterns.

    The cleaning process does not eliminate attack samples and
    does not force MQTT-specific fields to exist.
    """

    # --------------------------------------------------
    # 1. Remove rows without minimal network information
    # --------------------------------------------------
    # Records without source IP, destination IP, or packet length
    # cannot be used for traffic analysis
    df = df.dropna(subset=[
        "ip.src",
        "ip.dst",
        "frame.len"
    ])

    # --------------------------------------------------
    # 2. Normalize MQTT fields
    # --------------------------------------------------
    # Missing MQTT information usually indicates:
    # - Pure TCP traffic
    # - TCP handshake packets
    # - Possible SYN flooding attack traffic

    df["mqtt.msgtype"] = df["mqtt.msgtype"].fillna("NO_MQTT")
    df["mqtt.qos"] = df["mqtt.qos"].fillna(-1)
    df["mqtt.clientid"] = df["mqtt.clientid"].fillna("NONE")
    df["mqtt.topic"] = df["mqtt.topic"].fillna("NONE")

    # --------------------------------------------------
    # 3. RTT (Round Trip Time)
    # --------------------------------------------------
    # If ACK information is not available, RTT cannot be estimated
    # Therefore the value is replaced with zero
    df["tcp.analysis.ack_rtt"] = df["tcp.analysis.ack_rtt"].fillna(0)

    # --------------------------------------------------
    # 4. TCP Flags conversion
    # --------------------------------------------------
    # TShark exports TCP flags in hexadecimal format (e.g., 0x0002).
    # These values are converted into decimal representation
    # to make them suitable for machine learning algorithms.

    def parse_flags(x):
        try:
            # Convert hexadecimal string to integer
            return int(str(x), 16)
        except:
            # If conversion fails, return zero
            return 0

    # Create a new column containing the decimal representation
    df["tcp.flags.dec"] = df["tcp.flags"].apply(parse_flags)

    # --------------------------------------------------
    # 5. Numeric type conversion
    # --------------------------------------------------
    # These columns must be numeric for ML model training

    numeric_cols = [
        "frame.time_relative",
        "tcp.srcport",
        "tcp.dstport",
        "tcp.window_size_value",
        "tcp.analysis.ack_rtt",
        "frame.len",
        "mqtt.qos",
        "tcp.flags.dec"
    ]

    # Convert columns to numeric type
    # errors="coerce" converts invalid values to NaN
    # fillna(0) replaces NaN values with zero
    for col in numeric_cols:
        df[col] = pd.to_numeric(df[col], errors="coerce").fillna(0)

    # Return cleaned dataframe
    return df


# ======================================================
# PROCESS ALL CSV FILES
# ======================================================

# Search for all CSV files inside the raw CSV directory
csv_files = glob.glob(os.path.join(CSV_RAW_DIR, "*.csv"))

# Stop execution if no CSV files are found
if not csv_files:
    raise RuntimeError("No CSV files found in csv_raw directory")

# Process each CSV file
for file in csv_files:

    print(f"\nCleaning file: {os.path.basename(file)}")

    # Load raw CSV file into a dataframe
    df = pd.read_csv(file)

    # Record number of rows before cleaning
    rows_before = len(df)

    # Apply cleaning function
    df = clean_dataframe(df)

    # Record number of rows after cleaning
    rows_after = len(df)

    # Define output file path
    out_file = os.path.join(
        CSV_CLEAN_DIR,
        os.path.basename(file)
    )

    # Save cleaned dataframe as CSV
    df.to_csv(out_file, index=False)

    # Display cleaning statistics
    print(f"Rows before cleaning: {rows_before}")
    print(f"Rows after cleaning: {rows_after}")
    print(f"Clean CSV saved to: {out_file}")


# Final message
print("\nDATA CLEANING COMPLETED")